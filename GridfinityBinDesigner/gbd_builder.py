"""Fusion geometry for Gridfinity Bin Designer.

Base (parametric, named "GBD ..."):
  one foot (0.8 / 1.8 / 2.15 mm profile) patterned over the grid, and the
  outer block, driven by user parameters (NumUnitsX, GridPitch, HeightUnits, ...).
Layout (regenerated by the designer, named "GBD Layout ..."):
  join feet + block, cut the cavity with stacking lip, add the interior
  (dividers, label tabs, scoops) as one exact body, cut magnet/screw holes.

Fusion's internal length unit is the centimetre; this module works in mm and
converts at the API boundary.
"""

import json
import math
import os

import adsk.core
import adsk.fusion

import gbd_layout as L

ATTR_GROUP = 'GridfinityBinDesigner'
ATTR_CONFIG = 'config'
BIN_BODY = 'GridfinityBin'
LAYOUT_PREFIX = 'GBD Layout '


class BuildError(RuntimeError):
    pass


# ----------------------------------------------------------------- helpers
def _vi(expr):
    return adsk.core.ValueInput.createByString(expr)


def _p(x_mm, y_mm, z_mm=0.0):
    return adsk.core.Point3D.create(x_mm / 10.0, y_mm / 10.0, z_mm / 10.0)


def _v(x, y, z):
    return adsk.core.Vector3D.create(x, y, z)


def _coll(items):
    c = adsk.core.ObjectCollection.create()
    for i in items:
        c.add(i)
    return c


def _mm(design, name):
    p = design.userParameters.itemByName(name)
    if p is None:
        raise BuildError('user parameter %s is missing' % name)
    return p.value * 10.0


def _num(design, name):
    p = design.userParameters.itemByName(name)
    if p is None:
        raise BuildError('user parameter %s is missing' % name)
    return p.value


def _inside(body, x, y, z):
    return body.pointContainment(_p(x, y, z)) == adsk.fusion.PointContainment.PointInsidePointContainment


def _width_at(body, y, z, x_from, x_to, step=0.01):
    """Length of solid material along X at (y, z) between x_from and x_to (mm)."""
    n = int(round((x_to - x_from) / step))
    hits = sum(1 for k in range(n) if _inside(body, x_from + (k + 0.5) * step, y, z))
    return hits * step


# ------------------------------------------------------------- parameters
def _param_table(cfg):
    f = cfg['fit']
    mm = lambda v: '%g mm' % v  # noqa: E731
    return [
        ('NumUnitsX', str(cfg['nx']), '', 'Bin width in grid units'),
        ('NumUnitsY', str(cfg['ny']), '', 'Bin depth in grid units'),
        ('HeightUnits', str(cfg['heightUnits']), '', 'Bin height in height units (without the stacking lip)'),
        ('GridPitch', mm(f['GridPitch']), 'mm', 'Gridfinity grid pitch (spec: 42 mm)'),
        ('HeightUnit', mm(f['HeightUnit']), 'mm', 'Gridfinity height unit (spec: 7 mm)'),
        ('BinClearance', mm(f['BinClearance']), 'mm', 'Gap to the grid per side (spec: 0.25 mm)'),
        ('BinCornerRadius', '4 mm - BinClearance', 'mm', 'Outer corner radius (spec: 3.75 mm)'),
        ('FootMidWidth', 'GridPitch - 2 * BinClearance - 4.3 mm', 'mm', 'Width of the vertical band of each foot (spec: 37.2 mm)'),
        ('StackingLip', '1' if cfg['lip'] else '0', '', '1 = stacking lip, 0 = flat top'),
        ('LipHeight', '( 4.65 mm - BinClearance ) * StackingLip', 'mm', 'Stacking lip height (spec: 4.4 mm)'),
        ('BinHeight', 'HeightUnits * HeightUnit', 'mm', 'Nominal height, foot bottom to the top of the wall'),
        ('BinTotalHeight', 'BinHeight + LipHeight', 'mm', 'Overall height including the stacking lip'),
        ('WallThickness', mm(f['WallThickness']), 'mm', 'Outer wall thickness (press Update in the designer after changing)'),
        ('FloorHeight', mm(f['FloorHeight']), 'mm', 'Top of the inside floor (press Update after changing)'),
        ('DividerThickness', mm(cfg['divider']['thickness']), 'mm', 'Divider thickness (press Update after changing)'),
    ]


def apply_parameters(design, cfg):
    up = design.userParameters
    for name, expr, units, comment in _param_table(cfg):
        p = up.itemByName(name)
        if p is None:
            up.add(name, _vi(expr), units, comment)
        elif p.expression.replace(' ', '') != expr.replace(' ', ''):
            p.expression = expr


# ---------------------------------------------------------------- features
def _param_rect(sketch, x0, y0, x1, y1, x0_expr, y0_expr, w_expr, h_expr, name):
    """Fully constrained rectangle with expression-driven dimensions from the sketch origin."""
    sketch.name = name
    gc = sketch.geometricConstraints
    before = gc.count
    lines = sketch.sketchCurves.sketchLines.addTwoPointRectangle(_p(x0, y0), _p(x1, y1))
    if gc.count == before:
        for i in range(lines.count):
            ln = lines.item(i)
            a, b = ln.startSketchPoint.geometry, ln.endSketchPoint.geometry
            (gc.addHorizontal if abs(a.y - b.y) < 1e-7 else gc.addVertical)(ln)
    p00 = p11 = None
    for i in range(lines.count):
        ln = lines.item(i)
        for sp in (ln.startSketchPoint, ln.endSketchPoint):
            g = sp.geometry
            if abs(g.x - x0 / 10) < 1e-6 and abs(g.y - y0 / 10) < 1e-6:
                p00 = sp
            if abs(g.x - x1 / 10) < 1e-6 and abs(g.y - y1 / 10) < 1e-6:
                p11 = sp
    if p00 is None or p11 is None:
        raise BuildError('rectangle corners not found in ' + name)
    sd = sketch.sketchDimensions
    hor = adsk.fusion.DimensionOrientations.HorizontalDimensionOrientation
    ver = adsk.fusion.DimensionOrientations.VerticalDimensionOrientation
    sd.addDistanceDimension(sketch.originPoint, p00, hor, _p(x0 / 2, y0 - 6)).parameter.expression = x0_expr
    sd.addDistanceDimension(sketch.originPoint, p00, ver, _p(x0 - 6, y0 / 2)).parameter.expression = y0_expr
    sd.addDistanceDimension(p00, p11, hor, _p((x0 + x1) / 2, y0 - 10)).parameter.expression = w_expr
    sd.addDistanceDimension(p00, p11, ver, _p(x0 - 10, (y0 + y1) / 2)).parameter.expression = h_expr
    if not sketch.isFullyConstrained:
        raise BuildError('sketch not fully constrained: ' + name)
    return sketch


def _single_profile(sketch):
    if sketch.profiles.count != 1:
        raise BuildError('%s: expected 1 profile, got %d' % (sketch.name, sketch.profiles.count))
    return sketch.profiles.item(0)


def _extrude(comp, profile, dist_expr, name, start_offset=None, negative=False, taper='0 deg',
             op=adsk.fusion.FeatureOperations.NewBodyFeatureOperation):
    ext = comp.features.extrudeFeatures
    inp = ext.createInput(profile, op)
    direction = (adsk.fusion.ExtentDirections.NegativeExtentDirection if negative
                 else adsk.fusion.ExtentDirections.PositiveExtentDirection)
    inp.setOneSideExtent(adsk.fusion.DistanceExtentDefinition.create(_vi(dist_expr)), direction, _vi(taper))
    if start_offset:
        inp.startExtent = adsk.fusion.OffsetStartDefinition.create(_vi(start_offset))
    f = ext.add(inp)
    f.name = name
    return f


def _vertical_edges(body):
    out = []
    for e in body.edges:
        if isinstance(e.geometry, adsk.core.Line3D):
            a, b = e.startVertex.geometry, e.endVertex.geometry
            if abs(a.x - b.x) < 1e-7 and abs(a.y - b.y) < 1e-7:
                out.append(e)
    return out


def _fillet(comp, edges, radius_expr, name):
    fil = comp.features.filletFeatures
    inp = fil.createInput()
    inp.edgeSetInputs.addConstantRadiusEdgeSet(_coll(edges), _vi(radius_expr), False)
    f = fil.add(inp)
    f.name = name
    return f


def _flat_face_at(body, z_mm):
    found = [f for f in body.faces if isinstance(f.geometry, adsk.core.Plane) and
             abs(abs(f.geometry.normal.z) - 1) < 1e-7 and abs(f.pointOnFace.z * 10 - z_mm) < 1e-4]
    if len(found) != 1:
        raise BuildError('expected one flat face at z = %.3f mm, found %d' % (z_mm, len(found)))
    return found[0]


def _taper_extrude(comp, body, z_face, dist, inset_change, name):
    """Extrude the flat face of `body` at z_face by dist (mm, up if > 0 else down), changing the
    outline inset by inset_change (mm, > 0 = shrink). Joins to the body. The taper sign is checked
    against the measured result, because Fusion's sign convention depends on the face direction."""
    angle = math.degrees(math.atan2(abs(inset_change), abs(dist)))
    z_end = z_face + dist
    bb0 = body.boundingBox
    width_before = (bb0.maxPoint.x - bb0.minPoint.x) * 10
    for sign in ((1, -1) if inset_change else (0,)):
        face = _flat_face_at(body, z_face)
        ext = comp.features.extrudeFeatures
        inp = ext.createInput(face, adsk.fusion.FeatureOperations.JoinFeatureOperation)
        dirn = adsk.fusion.ExtentDirections.PositiveExtentDirection
        inp.setOneSideExtent(adsk.fusion.DistanceExtentDefinition.create(_vi('%r mm' % abs(dist))), dirn,
                             _vi('%r deg' % (sign * angle)))
        inp.participantBodies = [body]
        try:
            f = ext.add(inp)
        except RuntimeError:
            continue
        f.name = name
        bb = body.boundingBox
        zmin, zmax = bb.minPoint.z * 10, bb.maxPoint.z * 10
        grew_right_way = (zmax > z_face + 1e-4) if dist > 0 else (zmin < z_face - 1e-4)
        # outline at the far end: measure through the middle of the body
        cy = (bb.minPoint.y + bb.maxPoint.y) * 5
        zf = z_end - (0.02 if dist > 0 else -0.02)
        w_end = _width_at(body, cy, zf, bb.minPoint.x * 10 - 0.5, bb.maxPoint.x * 10 + 0.5, 0.02)
        w_face = _width_at(body, cy, z_face - (0.02 if dist > 0 else -0.02), bb.minPoint.x * 10 - 0.5,
                           bb.maxPoint.x * 10 + 0.5, 0.02)
        expected = w_face - 2 * inset_change * (abs(dist) - 0.02) / abs(dist)
        if grew_right_way and abs(w_end - expected) < 0.12:
            return f
        f.deleteMe()
    raise BuildError('%s: tapered extrude failed (start width %.2f mm)' % (name, width_before))


# ---------------------------------------------------------------- base
def build_base(design):
    """Parametric foot (patterned) and outer block. Returns the block body."""
    root = design.rootComponent
    xy = root.xYConstructionPlane
    p = _mm(design, 'GridPitch')
    c = _mm(design, 'BinClearance')
    nx, ny = int(round(_num(design, 'NumUnitsX'))), int(round(_num(design, 'NumUnitsY')))
    mid = _mm(design, 'FootMidWidth')
    total = _mm(design, 'BinTotalHeight')

    # 1. one foot: vertical band, then 45 degree tapers above and below
    off = (p - mid) / 2
    sk = _param_rect(root.sketches.add(xy), off, off, off + mid, off + mid,
                     '( GridPitch - FootMidWidth ) / 2', '( GridPitch - FootMidWidth ) / 2',
                     'FootMidWidth', 'FootMidWidth', 'GBD Foot Outline')
    foot = _extrude(root, _single_profile(sk), '%g mm' % L.FOOT_MIDDLE, 'GBD Foot Band',
                    start_offset='%g mm' % L.FOOT_BOTTOM).bodies.item(0)
    foot.name = 'Foot'
    _fillet(root, _vertical_edges(foot), 'BinCornerRadius - %g mm' % L.FOOT_TOP, 'GBD Foot Corners')
    _taper_extrude(root, foot, L.FOOT_BOTTOM + L.FOOT_MIDDLE, L.FOOT_TOP, -L.FOOT_TOP, 'GBD Foot Top')
    _taper_extrude(root, foot, L.FOOT_BOTTOM, -L.FOOT_BOTTOM, L.FOOT_BOTTOM, 'GBD Foot Bottom')
    rp = root.features.rectangularPatternFeatures
    pin = rp.createInput(_coll([foot]), root.xConstructionAxis, _vi('NumUnitsX'), _vi('GridPitch'),
                         adsk.fusion.PatternDistanceType.SpacingPatternDistanceType)
    pin.setDirectionTwo(root.yConstructionAxis, _vi('NumUnitsY'), _vi('GridPitch'))
    rp.add(pin).name = 'GBD Foot Pattern'

    # 2. outer block from the top of the feet to the top of the stacking lip
    sk = _param_rect(root.sketches.add(xy), c, c, nx * p - c, ny * p - c, 'BinClearance', 'BinClearance',
                     'NumUnitsX * GridPitch - 2 * BinClearance', 'NumUnitsY * GridPitch - 2 * BinClearance',
                     'GBD Block Outline')
    block = _extrude(root, _single_profile(sk), 'BinTotalHeight - %g mm' % L.FOOT_HEIGHT, 'GBD Block',
                     start_offset='%g mm' % L.FOOT_HEIGHT).bodies.item(0)
    block.name = BIN_BODY
    _fillet(root, _vertical_edges(block), 'BinCornerRadius', 'GBD Block Corners')
    if abs(block.boundingBox.maxPoint.z * 10 - total) > 1e-3:
        raise BuildError('block height mismatch')
    return block


# -------------------------------------------------------------- layout
def _combine(root, target, tools, op, name):
    cmb = root.features.combineFeatures
    ci = cmb.createInput(target, _coll(tools))
    ci.operation = op
    f = cmb.add(ci)
    f.name = name
    return f


def _bin_body(design):
    body = next((b for b in design.rootComponent.bRepBodies if b.name == BIN_BODY), None)
    if body is None:
        raise BuildError('the %s body was not found' % BIN_BODY)
    return body


def build_cavity(design, cfg):
    """Cavity tool from the floor to the top (inner wall, lip support and stacking lip), cut from the bin."""
    root = design.rootComponent
    g = L.derived(cfg)
    pts = L.cavity_profile(cfg)
    z0, i0 = pts[0]
    z1, i1 = pts[1]
    e = g['clearance'] + i0
    sk = root.sketches.add(root.xYConstructionPlane)
    _param_rect(sk, e, e, g['gridWidth'] - e, g['gridDepth'] - e, '%r mm' % e, '%r mm' % e,
                '%r mm' % (g['gridWidth'] - 2 * e), '%r mm' % (g['gridDepth'] - 2 * e), LAYOUT_PREFIX + 'Cavity Outline')
    tool = _extrude(root, _single_profile(sk), '%r mm' % (z1 - z0), LAYOUT_PREFIX + 'Cavity 1',
                    start_offset='%r mm' % z0).bodies.item(0)
    tool.name = 'CavityTool'
    _fillet(root, _vertical_edges(tool), '%r mm' % (g['outerRadius'] - i0), LAYOUT_PREFIX + 'Cavity Corners')
    for k, ((za, ia), (zb, ib)) in enumerate(zip(pts[1:], pts[2:]), start=2):
        _taper_extrude(root, tool, za, zb - za, ib - ia, LAYOUT_PREFIX + 'Cavity %d' % k)
    body = _bin_body(design)
    _combine(root, body, [tool], adsk.fusion.FeatureOperations.CutFeatureOperation, LAYOUT_PREFIX + 'Cut Cavity')
    return body


def _tbm():
    return adsk.fusion.TemporaryBRepManager.get()


def _box(x0, y0, z0, x1, y1, z1):
    obb = adsk.core.OrientedBoundingBox3D.create(_p((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2),
                                                 _v(1, 0, 0), _v(0, 1, 0),
                                                 (x1 - x0) / 10, (y1 - y0) / 10, (z1 - z0) / 10)
    return _tbm().createBox(obb)


def _tab_solid(t):
    """Label tab: a block under the label surface, cut by the 45-degree (configurable) support plane."""
    tbm = _tbm()
    y_face, depth, h, z_top = t['yFace'], t['depth'], t['height'], t['zTop']
    solid = _box(t['x0'], y_face - depth, z_top - h, t['x1'], y_face + L.OVERLAP, z_top)
    # underside plane through the wall at the tab bottom and the front edge at (top - thickness)
    p0 = (y_face, z_top - h)
    p1 = (y_face - depth, z_top - L.TAB_THICKNESS)
    uy, uz = p1[0] - p0[0], p1[1] - p0[1]
    ln = math.hypot(uy, uz)
    uy, uz = uy / ln, uz / ln
    # normal (in YZ) pointing to the material side (up)
    ny_, nz_ = -uz, uy
    if nz_ < 0:
        ny_, nz_ = -ny_, -nz_
    size = 400.0
    mid = ((p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2)
    centre = _p((t['x0'] + t['x1']) / 2, mid[0] - ny_ * size / 2, mid[1] - nz_ * size / 2)
    cutter = tbm.createBox(adsk.core.OrientedBoundingBox3D.create(
        centre, _v(1, 0, 0), _v(0, uy, uz), (t['x1'] - t['x0'] + 2) / 10, size / 10, size / 10))
    if not tbm.booleanOperation(solid, cutter, adsk.fusion.BooleanTypes.DifferenceBooleanType):
        raise BuildError('label tab boolean failed')
    return solid


def _scoop_solid(s):
    """Finger scoop: a block in the front-bottom corner of a compartment minus a cylinder."""
    tbm = _tbm()
    r, y, z = s['radius'], s['yFace'], s['zFloor']
    solid = _box(s['x0'], y - L.OVERLAP, z - L.OVERLAP, s['x1'], y + r, z + r)
    cyl = tbm.createCylinderOrCone(_p(s['x0'] - 1, y + r, z + r), r / 10, _p(s['x1'] + 1, y + r, z + r), r / 10)
    if not tbm.booleanOperation(solid, cyl, adsk.fusion.BooleanTypes.DifferenceBooleanType):
        raise BuildError('scoop boolean failed')
    return solid


def interior_solid(cfg):
    """Union of dividers, label tabs and scoops as a temporary body (or None)."""
    g = L.derived(cfg)
    parts = [_box(x0, y0, g['floor'] - L.OVERLAP, x1, y1, g['dividerTop']) for x0, y0, x1, y1 in L.divider_boxes(cfg)]
    parts += [_tab_solid(t) for t in L.label_tabs(cfg)]
    parts += [_scoop_solid(s) for s in L.scoops(cfg)]
    if not parts:
        return None
    union = parts[0]
    for b in parts[1:]:
        if not _tbm().booleanOperation(union, b, adsk.fusion.BooleanTypes.UnionBooleanType):
            raise BuildError('interior union failed')
    return union


def holes_solid(cfg):
    pts = L.hole_centres(cfg)
    if not pts:
        return None
    f, tbm = cfg['fit'], _tbm()
    union = None
    for x, y in pts:
        tools = []
        if cfg['holes'] in ('magnets', 'both'):
            tools.append(tbm.createCylinderOrCone(_p(x, y, -1), f['MagnetDiameter'] / 20, _p(x, y, f['MagnetDepth']), f['MagnetDiameter'] / 20))
        if cfg['holes'] in ('screws', 'both'):
            tools.append(tbm.createCylinderOrCone(_p(x, y, -1), f['ScrewDiameter'] / 20, _p(x, y, f['ScrewDepth']), f['ScrewDiameter'] / 20))
        for t in tools:
            if union is None:
                union = t
            elif not tbm.booleanOperation(union, t, adsk.fusion.BooleanTypes.UnionBooleanType):
                raise BuildError('hole union failed')
    return union


def _add_base_feature(root, temp_body, name, body_name):
    bf = root.features.baseFeatures.add()
    bf.name = name
    bf.startEdit()
    root.bRepBodies.add(temp_body, bf)
    bf.finishEdit()
    body = bf.bodies.item(0)
    body.name = body_name
    return body


def build_layout(design, cfg):
    """Everything after the parametric base. Returns per-stage volumes (cm3) for verification."""
    root = design.rootComponent
    body = _bin_body(design)
    feet = [b for b in root.bRepBodies if b.name.startswith('Foot')]
    _combine(root, body, feet, adsk.fusion.FeatureOperations.JoinFeatureOperation, LAYOUT_PREFIX + 'Join Feet')
    build_cavity(design, cfg)
    stages = {'base': body.volume}
    interior = interior_solid(cfg)
    if interior is not None:
        tool = _add_base_feature(root, interior, LAYOUT_PREFIX + 'Interior', 'Interior')
        _combine(root, body, [tool], adsk.fusion.FeatureOperations.JoinFeatureOperation, LAYOUT_PREFIX + 'Join Interior')
    stages['interior'] = body.volume
    holes = holes_solid(cfg)
    if holes is not None:
        tool = _add_base_feature(root, holes, LAYOUT_PREFIX + 'Holes', 'Holes')
        _combine(root, body, [tool], adsk.fusion.FeatureOperations.CutFeatureOperation, LAYOUT_PREFIX + 'Cut Holes')
    stages['final'] = body.volume
    return stages


def remove_layout(design):
    """Delete every 'GBD Layout ...' item, newest first."""
    tl = design.timeline
    for i in range(tl.count - 1, -1, -1):
        item = tl.item(i)
        if item.name.startswith(LAYOUT_PREFIX):
            item.entity.deleteMe()


# ----------------------------------------------------------- persistence
def save_config(design, cfg):
    design.attributes.add(ATTR_GROUP, ATTR_CONFIG, json.dumps(cfg))


def load_config(design):
    a = design.attributes.itemByName(ATTR_GROUP, ATTR_CONFIG)
    if a is None:
        return None
    try:
        return json.loads(a.value)
    except ValueError:
        return None


def is_designer_bin(design):
    return (design is not None and load_config(design) is not None and
            any(b.name == BIN_BODY for b in design.rootComponent.bRepBodies))


# ------------------------------------------------------------ public API
def create_bin(app, cfg):
    """Build a complete bin in a new document. Returns (document, report)."""
    cfg = L.normalize(cfg)
    doc = app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
    design = adsk.fusion.Design.cast(app.activeProduct)
    design.designType = adsk.fusion.DesignTypes.ParametricDesignType
    design.fusionUnitsManager.distanceDisplayUnits = adsk.fusion.DistanceUnits.MillimeterDistanceUnits
    apply_parameters(design, cfg)
    build_base(design)
    stages = build_layout(design, cfg)
    save_config(design, cfg)
    return doc, verify(design, cfg, stages)


def update_bin(design, cfg):
    """Re-size and re-layout a designer bin in place."""
    cfg = L.normalize(cfg)
    if not is_designer_bin(design):
        raise BuildError('The active document is not a bin made by Gridfinity Bin Designer. Use "Create new bin".')
    remove_layout(design)
    apply_parameters(design, cfg)
    stages = build_layout(design, cfg)
    save_config(design, cfg)
    return verify(design, cfg, stages)


def verify(design, cfg, stages=None):
    """Read-back checks: one solid of the right size and volume, spec profile, dividers, holes."""
    root = design.rootComponent
    bodies = list(root.bRepBodies)
    main = next((b for b in bodies if b.name == BIN_BODY), None)
    tl = design.timeline
    report = {
        'bodies': [b.name for b in bodies],
        'unhealthy': [tl.item(i).name for i in range(tl.count)
                      if tl.item(i).healthState != adsk.fusion.FeatureHealthStates.HealthyFeatureHealthState],
        'compartments': len(L.compartments(cfg)),
        'problems': [],
    }
    problems = report['problems']
    if main is None:
        problems.append('bin body missing')
        return report
    g = L.derived(cfg)
    bb = main.boundingBox
    report['size_mm'] = [round((bb.maxPoint.x - bb.minPoint.x) * 10, 3), round((bb.maxPoint.y - bb.minPoint.y) * 10, 3),
                         round((bb.maxPoint.z - bb.minPoint.z) * 10, 3)]
    report['volume_cm3'] = round(main.volume, 4)
    report['mass_g_pla'] = round(main.volume * 1.24, 1)
    report['lumps'] = main.lumps.count
    expected = [round(g['width'], 3), round(g['depth'], 3), round(g['top'], 3)]
    if any(abs(a - b) > 0.01 for a, b in zip(report['size_mm'], expected)):
        problems.append('size %s mm differs from the expected %s mm' % (report['size_mm'], expected))
    if len(bodies) != 1 or main.lumps.count != 1:
        problems.append('expected one single-piece body, found %s' % report['bodies'])
    if report['unhealthy']:
        problems.append('features with errors or warnings: %s' % ', '.join(report['unhealthy']))
    if stages:
        exp_base = L.base_volume(cfg) / 1000
        if abs(stages['base'] - exp_base) > 0.002:
            problems.append('base volume %.4f cm3 differs from the spec value %.4f cm3' % (stages['base'], exp_base))
        if not L.label_tabs(cfg) and not L.scoops(cfg):
            exp_div = L.divider_volume_added(cfg, 2000) / 1000
            if abs(stages['interior'] - stages['base'] - exp_div) > 0.01:
                problems.append('dividers add %.4f cm3, expected %.4f cm3' % (stages['interior'] - stages['base'], exp_div))
        exp_holes = L.hole_volume(cfg) / 1000
        if abs(stages['interior'] - stages['final'] - exp_holes) > 0.002:
            problems.append('holes remove %.4f cm3, expected %.4f cm3' % (stages['interior'] - stages['final'], exp_holes))
    # spec profile: feet and the cavity/lip insets, probed through the first cell
    cx = g['pitch'] / 2
    for z, half in ((0.05, g['footBottomWidth'] / 2 + 0.05), (1.7, g['footMidWidth'] / 2), (4.7, g['footTopWidth'] / 2 - 0.05)):
        y = g['pitch'] / 2 + 0.31 + (9.0 if cfg['holes'] != 'none' else 0)  # off the hole centres
        if not _inside(main, cx - half + 0.15, y, z) or _inside(main, cx - half - 0.15, y, z):
            problems.append('foot profile is off at z = %.2f mm' % z)
            break
    ymid = g['gridDepth'] / 2 + 0.23
    pts = L.cavity_profile(cfg)
    for (za, ia), (zb, ib) in zip(pts, pts[1:]):
        z = (za + zb) / 2
        if zb - za < 0.3:
            continue
        i = (ia + ib) / 2
        x_face = g['clearance'] + i
        blockers = [(b[0], b[1], b[2], b[3]) for b in L.divider_boxes(cfg)]
        blockers += [(t['x0'], t['yFace'] - t['depth'], t['x1'], t['yFace']) for t in L.label_tabs(cfg)]
        blockers += [(s['x0'], s['yFace'], s['x1'], s['yFace'] + s['radius']) for s in L.scoops(cfg)]
        clear_of_layout = all(not (b[0] - 0.5 < x_face + 0.4 and b[1] - 0.5 < ymid < b[3] + 0.5) for b in blockers)
        if not clear_of_layout:
            continue
        if not _inside(main, x_face - 0.15, ymid, z) or (i > 0.2 and _inside(main, x_face + 0.15, ymid, z)):
            problems.append('wall or lip profile is off at z = %.2f mm' % z)
            break
    zmid = (g['floor'] + g['dividerTop']) / 2
    for x0, y0, x1, y1 in L.divider_boxes(cfg):
        if not _inside(main, (x0 + x1) / 2, (y0 + y1) / 2, zmid):
            problems.append('divider missing at (%.1f, %.1f)' % ((x0 + x1) / 2, (y0 + y1) / 2))
    scoop_top = g['floor'] + max([s['radius'] for s in L.scoops(cfg)] + [0])
    tab_bottom = g['dividerTop'] - (g['tabHeight'] if cfg['tabs']['enabled'] else 0)
    if tab_bottom - scoop_top > 0.6:
        zfree = (scoop_top + tab_bottom) / 2
        for comp in L.compartments(cfg):
            x, y = comp['probe']
            if _inside(main, x, y, zfree):
                problems.append('compartment not empty at (%.1f, %.1f)' % (x, y))
    for t in L.label_tabs(cfg):
        if not _inside(main, (t['x0'] + t['x1']) / 2, t['yFace'] - 1.0, t['zTop'] - 0.4):
            problems.append('label tab missing at x = %.1f' % ((t['x0'] + t['x1']) / 2))
    for s in L.scoops(cfg):
        if not _inside(main, (s['x0'] + s['x1']) / 2, s['yFace'] + 0.4, s['zFloor'] + 0.4):
            problems.append('scoop missing at x = %.1f' % ((s['x0'] + s['x1']) / 2))
    f = cfg['fit']
    for x, y in L.hole_centres(cfg):
        depth = f['ScrewDepth'] if cfg['holes'] in ('screws', 'both') else f['MagnetDepth']
        if _inside(main, x, y, 0.3) or _inside(main, x, y, depth - 0.3) or not _inside(main, x, y, depth + 0.3):
            problems.append('hole wrong at (%.1f, %.1f)' % (x, y))
    return report


def next_version_path(folder, stem, ext):
    n = 1
    while True:
        p = os.path.join(folder, '%s-v%d.%s' % (stem, n, ext))
        if not os.path.exists(p):
            return p
        n += 1


def export_body(design, path, fmt):
    root = design.rootComponent
    body = _bin_body(design)
    was_visible = body.isLightBulbOn
    body.isLightBulbOn = True
    try:
        em = design.exportManager
        if fmt == 'stl':
            opt = em.createSTLExportOptions(body, path)
            opt.isBinaryFormat = True
            opt.meshRefinement = adsk.fusion.MeshRefinementSettings.MeshRefinementHigh
        elif fmt == '3mf':
            opt = em.createC3MFExportOptions(body, path)
        elif fmt == 'step':
            opt = em.createSTEPExportOptions(path, root)
        else:
            raise BuildError('unknown export format ' + fmt)
        ok = em.execute(opt)
    finally:
        body.isLightBulbOn = was_visible
    if not ok or not os.path.exists(path) or os.path.getsize(path) == 0:
        raise BuildError('export failed: ' + path)
    return path, os.path.getsize(path)
